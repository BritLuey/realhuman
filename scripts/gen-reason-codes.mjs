// Regenerates the tables in docs/reference/reason-codes.md from the code, so titles, descriptions and
// weights can't drift from what the engine does. Run after `pnpm build`:
//
//   node scripts/gen-reason-codes.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { WEIGHTS } from '../packages/engine/dist/index.js';
import { REASONS } from '../packages/schema/dist/index.js';

const fmt = (n) => String(Math.abs(n));

/** The weight column: how strongly each code counts, in the units used by the evidence levels. */
function weightOf(code, info) {
  if (info.group === 'gate') return 'gate';
  if (code === 'headless_markers') {
    return `${fmt(WEIGHTS.headlessPerMarker)} per trait (${fmt(WEIGHTS.noBrowserUi)} for \`no_browser_ui\`, ${fmt(WEIGHTS.zeroOuterSize)} for \`zero_outer_size\`), at most ${fmt(WEIGHTS.headlessMax)}`;
  }
  if (code === 'ja4_non_browser') {
    return `${fmt(WEIGHTS.ja4_non_browser)}, or ${fmt(WEIGHTS.ja4KnownNonBrowser)} if listed in \`ja4.nonBrowser\``;
  }
  const weight = WEIGHTS[code];
  return typeof weight === 'number' ? fmt(weight) : '–';
}

const GROUPS = [
  [
    'gate',
    'Gates',
    'Conclusive on their own. If any gate fires, the label is `bot` with `conclusive` bot evidence, and `engine` is `gate`.',
  ],
  [
    'environment',
    'Environment',
    'What the browser says about itself, and whether that story is consistent.',
  ],
  ['network', 'Network', 'Evidence from the TLS connection and HTTP headers, read at the edge.'],
  ['behaviour', 'Behaviour', 'How the person, or program, interacted with the page.'],
  ['engine', 'Engine', 'How the decision was produced.'],
];

const sections = GROUPS.map(([group, heading, intro]) => {
  const rows = Object.entries(REASONS)
    .filter(([, info]) => info.group === group)
    .map(
      ([code, info]) =>
        `| \`${code}\` | ${info.title} | ${info.lean} | ${weightOf(code, info)} | ${info.description} |`,
    );
  return `## ${heading}\n\n${intro}\n\n| Code | Title | Lean | Weight | Meaning |\n|---|---|---|---|---|\n${rows.join('\n')}\n`;
}).join('\n');

const path = new URL('../docs/reference/reason-codes.md', import.meta.url);
const doc = readFileSync(path, 'utf8');
const start = doc.indexOf('<!-- generated:start -->');
const end = doc.indexOf('<!-- generated:end -->');
if (start === -1 || end === -1) throw new Error('reason-codes.md is missing the generated markers');
writeFileSync(
  path,
  `${doc.slice(0, start)}<!-- generated:start -->\n<!-- Generated by scripts/gen-reason-codes.mjs. Edit the code, then re-run it. -->\n\n${sections}\n${doc.slice(end)}`,
);
console.log('docs/reference/reason-codes.md updated');
